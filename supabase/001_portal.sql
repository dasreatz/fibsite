-- FIB Olymp: game community membership. Run as project owner in SQL Editor.
-- All application/contact data stays server-side, never in the browser database API.
begin;
create table if not exists public.fib_applications (
 id text primary key, rp_name text not null, email text not null, experience text not null, motivation text not null,
 code_hash text not null, status text not null default 'pending' check (status in ('pending','approved','rejected','registering','registered')),
 created_at timestamptz not null default now(), decided_at timestamptz, decided_by uuid references auth.users(id), reason text,
 invite_hash text unique, invite_expires_at timestamptz, invite_used_at timestamptz,
 telegram_hash text unique, telegram_expires_at timestamptz, telegram_chat text, email_delivery text, telegram_delivery text
);
create unique index if not exists fib_active_email on public.fib_applications(lower(email)) where status in ('pending','approved','registering');
create table if not exists public.fib_members (
 user_id uuid primary key references auth.users(id) on delete cascade, application_id text unique references public.fib_applications(id),
 rp_name text not null, rank integer not null default 1 check(rank between 1 and 12),
 unit text check(unit in ('ЦСО «А»','ДКБ','ГСУ','ГУР')), position text check(position in ('Агент','Заступник','Керівник')),
 active boolean not null default true, joined_at timestamptz not null default now(), check((unit is null)=(position is null))
);
create unique index if not exists fib_one_director on public.fib_members(rank) where rank=12 and active;
create unique index if not exists fib_one_unit_lead on public.fib_members(unit,position) where position in ('Керівник','Заступник') and active;
create table if not exists public.fib_lessons(id bigint generated by default as identity primary key,title text not null unique,body text not null);
create table if not exists public.fib_progress(user_id uuid references public.fib_members(user_id) on delete cascade,lesson_id bigint references public.fib_lessons(id) on delete cascade,completed_at timestamptz default now(),primary key(user_id,lesson_id));
create table if not exists public.fib_audit(id bigint generated always as identity primary key,actor uuid references auth.users(id),action text not null,subject text,created_at timestamptz not null default now());
-- Explicit server-only access. No broad RLS policies or public storage buckets.
alter table public.fib_applications enable row level security;
alter table public.fib_members enable row level security;
alter table public.fib_lessons enable row level security;
alter table public.fib_progress enable row level security;
alter table public.fib_audit enable row level security;
revoke all on public.fib_applications,public.fib_members,public.fib_lessons,public.fib_progress,public.fib_audit from anon,authenticated;
grant select,insert,update,delete on public.fib_applications,public.fib_members,public.fib_lessons,public.fib_progress,public.fib_audit to service_role;
grant usage,select on sequence public.fib_lessons_id_seq,public.fib_audit_id_seq to service_role;
insert into public.fib_lessons(title,body) values
 ('Правила спільноти','Ознайомтеся з правилами сервера. Поважайте інших учасників та не публікуйте реальні особисті дані гравців.'),
 ('Структура та субординація','Ознайомтеся з ієрархією FIB Olymp, правилами спілкування та розподілом повноважень у грі.'),
 ('Робота з кабінетом','Перевірте власний профіль, ознайомтеся з оголошеннями спільноти та звертайтеся до наставника з питаннями.') on conflict(title) do nothing;
commit;
